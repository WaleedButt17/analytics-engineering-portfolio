CREATE OR REPLACE VIEW `your-project.staging.stg_cc_transactions`
AS WITH combined AS (
  SELECT
    CAST(NULL AS TIMESTAMP) AS ingested_at,
    CAST(transaction_id AS INT64) AS transaction_id,
    CAST(parent_txn_id AS INT64) AS parent_txn_id,
    order_id,
    CAST(NULL AS INT64) AS actual_order_id,
    CAST(customer_id AS INT64) AS customer_id,
    campaign_id,
    campaign_name,
    order_type,
    txn_type,
    response_type,
    response_text,
    total_amount,
    surcharge,
    billing_cycle_number,
    recycle_number,
    CAST(merchant_id AS INT64) AS merchant_id,
    merchant,
    CAST(NULL AS STRING) AS merchant_descriptor,
    CAST(NULL AS INT64) AS cascade_id,
    pay_source,
    card_type,
    CAST(NULL AS STRING) AS card_bin,
    card_last4,
    CAST(NULL AS BOOL) AS card_is_prepaid,
    CAST(NULL AS BOOL) AS card_is_debit,
    CAST(NULL AS STRING) AS avs_response,
    CAST(NULL AS STRING) AS cvv_response,
    CAST(NULL AS BOOL) AS is_chargedback,
    CAST(NULL AS FLOAT64) AS chargeback_amount,
    CAST(NULL AS DATE) AS chargeback_date,
    CAST(NULL AS STRING) AS chargeback_reason_code,
    CAST(NULL AS STRING) AS chargeback_note,
    CAST(NULL AS STRING) AS refund_reason,
    country,
    currency_code,
    CAST(NULL AS STRING) AS ip_address,
    utm_source,
    utm_medium,
    utm_campaign,
    CAST(NULL AS STRING) AS utm_term,
    CAST(NULL AS STRING) AS utm_content,
    CAST(NULL AS STRING) AS custom1,
    CAST(NULL AS STRING) AS custom2,
    CAST(NULL AS STRING) AS funnel_reference_id,
    item_count,
    item_names,
    item_skus,
    CAST(date_created AS TIMESTAMP) AS date_created,
    CAST(date_updated AS TIMESTAMP) AS date_updated,
    'historical' AS data_source
  FROM `your-project.raw.historical_cc_transactions`

  UNION ALL

  SELECT
    ingested_at,
    transaction_id,
    parent_txn_id,
    order_id,
    actual_order_id,
    customer_id,
    campaign_id,
    campaign_name,
    order_type,
    txn_type,
    response_type,
    response_text,
    total_amount,
    surcharge,
    billing_cycle_number,
    recycle_number,
    merchant_id,
    merchant,
    merchant_descriptor,
    cascade_id,
    pay_source,
    card_type,
    card_bin,
    card_last4,
    card_is_prepaid,
    card_is_debit,
    avs_response,
    cvv_response,
    is_chargedback,
    chargeback_amount,
    chargeback_date,
    chargeback_reason_code,
    chargeback_note,
    refund_reason,
    country,
    currency_code,
    ip_address,
    utm_source,
    utm_medium,
    utm_campaign,
    utm_term,
    utm_content,
    custom1,
    custom2,
    funnel_reference_id,
    item_count,
    item_names,
    item_skus,
    date_created,
    date_updated,
    'daily' AS data_source
  FROM `your-project.raw.daily_cc_transactions`
)

SELECT * FROM combined
QUALIFY ROW_NUMBER() OVER (PARTITION BY transaction_id ORDER BY data_source DESC) = 1;
